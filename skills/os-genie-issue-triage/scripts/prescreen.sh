#!/usr/bin/env bash
# Pre-screen one issue BEFORE any agent spends time on it.
# Usage: prescreen.sh <owner/repo> <issue-number>
# Prints one JSON line: {issue, verdict, reasons[], approval[], last_maintainer_comment_days}
# verdict: PASS | REJECT. Needs gh (authed) + jq. Read-only: never posts anything.
set -uo pipefail
repo=$1; n=$2
now=$(date -u +%s)

iss=$(gh issue view "$n" --repo "$repo" --json state,assignees,labels,comments,updatedAt,title,body)
reasons=(); approval=()

[ "$(jq -r .state <<<"$iss")" = OPEN ] || reasons+=("not open")
[ "$(jq '.assignees|length' <<<"$iss")" -eq 0 ] || reasons+=("assigned")

# one timeline call: open PRs and merged PRs that cross-reference the issue
tl=$(gh api "repos/$repo/issues/$n/timeline" --paginate \
  --jq '.[]|select(.event=="cross-referenced" and .source.issue.pull_request!=null)|[.source.issue.state,(.source.issue.pull_request.merged_at!=null)]|@tsv' 2>/dev/null)
xref=$(printf '%s\n' "$tl" | grep -c '^open' || true)
hits=0
[ "${xref:-0}" -eq 0 ] || reasons+=("open PR exists (xref=$xref)")

# already fixed: a MERGED PR cross-references the issue, or the title/body signals non-code work
merged=$(printf '%s\n' "$tl" | grep -c 'true$' || true)
[ "${merged:-0}" -eq 0 ] || reasons+=("merged PR already references it (likely fixed)")
nc_re='(saas|production cluster|our cluster|rfc|design doc|epic|umbrella|tracking issue|roadmap|brainstorm|investigate whether|decide (how|whether))'
jq -e --arg re "$nc_re" '(.title+" "+(.body//"")[0:600])|test($re;"i")' <<<"$iss" >/dev/null && reasons+=("looks like design/ops/tracking work, not a code fix")
jq -e --arg me "$repo" '(.body//"")|test("(moved to|now (lives|in)|see) (https://github.com/)?[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+";"i")' <<<"$iss" >/dev/null && reasons+=("body points at another repo")

# recent non-maintainer claimants (45d) and maintainer doubt / approval
claim_re='(i.?ll take|pick (this|it) up|would like to (work|take|pick|contribute)|i.?d (love|like) to (work|take|pick|help|fix)|let me (take|work|try)|i can (work|fix|help)|working on (this|it)|i will (work|fix|take|submit|open)|i can take|work on (this|it)|assign (this|me|it)|can i (take|work|try)|i.?d like to (work|take|fix)|i.?m working|claim)'
doubt_re="(not sure (we|if)|don.?t know if|do we want|not convinced|probably not|wontfix|won.?t fix|lint rule|prefer not|reluctant|not a priority|closed, not accepted|written by a human|not (written )?by an? (LLM|AI)|no (LLM|AI)s?\\b|human[- ]written|without (an? )?(LLM|AI))"
okay_re='(pr welcome|happy to (review|accept)|go ahead|please (send|open|submit)|sounds good|feel free to (open|submit|send)|contributions? welcome|confirmed)'

claimants=$(jq --argjson now "$now" --arg re "$claim_re" '[.comments[]
  | select(.authorAssociation as $a | ["OWNER","MEMBER","COLLABORATOR"]|index($a)|not)
  | select((.createdAt|fromdateiso8601) > $now-45*86400)
  | select(.body|test($re;"i"))]|length' <<<"$iss")
[ "$claimants" -eq 0 ] || reasons+=("$claimants recent claimant comment(s) <45d")

maint=$(jq '[.comments[]|select(.authorAssociation as $a|["OWNER","MEMBER","COLLABORATOR"]|index($a))]' <<<"$iss")
jq -e --arg re "$doubt_re" 'any(.[];.body|test($re;"i"))' <<<"$maint" >/dev/null && reasons+=("maintainer doubt language")
jq -e --arg re "$okay_re" 'any(.[];.body|test($re;"i"))' <<<"$maint" >/dev/null && approval+=("maintainer comment: welcome/confirmed")
for l in $(jq -r '.labels[].name' <<<"$iss" | tr ' ' '_'); do
  case "$(printf %s "$l" | tr A-Z a-z)" in *accepted*|*approved*|*triaged*|*confirmed*|*help_wanted*|*good_first*) approval+=("label:$l");; esac
done

# deeper checks, only if everything above passed (search API is 30/min): merged or design-rejected/AI-rejected PRs mentioning the issue
if [ "${#reasons[@]}" -eq 0 ]; then
  prs=""
  for try in 1 2 3 4; do
    sleep 2.5
    prs=$(gh api -X GET search/issues -f q="repo:$repo is:pr $n in:title,body" -f per_page=20 --jq '[.items[]|select(.pull_request!=null)|{n:.number,state:.state,merged:(.pull_request.merged_at!=null),title:.title}]' 2>/dev/null) && [ -n "$prs" ] && break
    prs=""; sleep 20
  done
  [ -n "$prs" ] || { prs='[]'; reasons+=("search unavailable (rate limit), cannot confirm no merged/open PR"); }
  [ "$(jq '[.[]|select(.merged)]|length' <<<"$prs")" -eq 0 ] || reasons+=("merged PR mentions it (likely fixed)")
  [ "$(jq '[.[]|select(.state=="open")]|length' <<<"$prs")" -eq 0 ] || reasons+=("open PR mentions it")
  for pn in $(jq -r '[.[]|select(.state=="closed" and (.merged|not))|.n][:3][]' <<<"$prs"); do
    sleep 1
    if gh api "repos/$repo/issues/$pn/comments" --jq '.[].body' 2>/dev/null | grep -qiE "(ai.generated|llm|generated by (an )?ai|rethink|brainstorm|not (the )?(right|desired) (approach|design)|design (is|isn.?t)|we don.?t want|won.?t accept|not accepting)"; then
      reasons+=("closed PR #$pn was rejected for AI/design reasons"); break
    fi
  done
fi

# repo AI-policy gate (README / CONTRIBUTING / AI policy files) - only for issues still passing
if [ "${#reasons[@]}" -eq 0 ]; then
  ban_re="(AI|LLM|LLMs|generative)[- ]?(generated|assisted)?[^.\n]{0,60}(not (permitted|allowed|accepted)|are banned|is banned|prohibited|forbidden|will be (closed|rejected))|no (LLM|AI)s?\b|written by a human|(PR|pull request) descriptions[^.\n]{0,80}(from|by) humans|to be from humans|must be performed by humans|including the submission of (PRs|pull requests)|not an? (LLM|AI)\b|(do not|don.?t) (use|submit)[^.\n]{0,40}(AI|LLM)"
  for f in README.md CONTRIBUTING.md .github/CONTRIBUTING.md AI_POLICY.md .github/AI_POLICY.md AGENTS.md; do
    txt=$(gh api "repos/$repo/contents/$f" --jq .content 2>/dev/null | base64 -d 2>/dev/null) || continue
    if printf '%s' "$txt" | grep -qiE "$ban_re"; then reasons+=("repo AI policy may forbid AI contributions ($f)"); break; fi
    if printf '%s' "$txt" | grep -qiE "(assign(ed)? (to you )?(before|first)|must be assigned|wait (for|until)[^.\n]{0,30}assign|human[- ]authored attestation)"; then reasons+=("repo requires assignment/attestation first ($f)"); break; fi
  done
fi

# PR-template attestation gate: boxes/sentences an AI cannot truthfully tick
if [ "${#reasons[@]}" -eq 0 ]; then
  att_re="(must be performed by humans|including the submission of (PRs|pull requests)|without relying on an? (AI|LLM)|can explain (them|these|it)[^.\n]{0,40}without|i (wrote|authored)[^.\n]{0,30}(myself|by hand)|human[- ]authored|tested (my changes )?on a live (environment|cluster)|not (generated|written) (by|with) (an? )?(AI|LLM))"
  for f in .github/pull_request_template.md .github/PULL_REQUEST_TEMPLATE.md pull_request_template.md PULL_REQUEST_TEMPLATE.md docs/pull_request_template.md; do
    txt=$(gh api "repos/$repo/contents/$f" --jq .content 2>/dev/null | base64 -d 2>/dev/null) || continue
    [ -n "$txt" ] || continue
    if printf '%s' "$txt" | grep -qiE "$att_re"; then reasons+=("PR template has an authorship/live-test attestation an agent cannot give ($f)"); fi
    break
  done
fi

last=$(jq -r --argjson now "$now" '[.[]|.createdAt|fromdateiso8601]|max // null|if .==null then null else (($now-.)/86400|floor) end' <<<"$maint")
[ "${#approval[@]}" -gt 0 ] || reasons+=("no maintainer approval signal")
[ "$last" = null ] || [ "$last" -le 180 ] || reasons+=("maintainer silent ${last}d")

verdict=PASS; [ "${#reasons[@]}" -eq 0 ] || verdict=REJECT
jq -nc --arg i "$repo#$n" --arg v "$verdict" --arg last "$last" \
  --argjson r "$(printf '%s\n' "${reasons[@]:-}" | jq -R . | jq -sc 'map(select(.!=""))')" \
  --argjson a "$(printf '%s\n' "${approval[@]:-}" | jq -R . | jq -sc 'map(select(.!=""))')" \
  '{issue:$i,verdict:$v,reasons:$r,approval:$a,last_maintainer_comment_days:(try ($last|tonumber) catch null)}'
